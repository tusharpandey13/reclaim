// Types and a precompiled validator from docs/contracts/snapshot-v2.schema.json. The page's CSP forbids
// compiling a schema at run time, so ajv does it here. Run `npm run contract` after changing the schema;
// a test fails if these files drift from it.
import { readFileSync, writeFileSync } from 'node:fs';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const SCHEMA = new URL('../../../docs/contracts/snapshot-v2.schema.json', import.meta.url);
const OUT = new URL('../src/generated/', import.meta.url);
const HEADER = '// Generated by scripts/gen-contract.mjs from snapshot-v2.schema.json. Do not edit.\n';

export function makeAjv(options = {}) {
  return new Ajv2020({ allErrors: false, allowUnionTypes: true, strict: true, unicodeRegExp: false, inlineRefs: false, ...options });
}

function tsType(node) {
  if (node.$ref) return node.$ref.split('/').pop();
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (node.anyOf) return node.anyOf.map(tsType).join(' | ');
  if (Array.isArray(node.type)) return node.type.map((type) => tsType({ ...node, type })).join(' | ');
  switch (node.type) {
    case 'string': return 'string';
    case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': {
      const inner = tsType(node.items);
      return inner.includes(' | ') ? `(${inner})[]` : `${inner}[]`;
    }
    case 'object': return node.properties ? inlineObject(node) : `Record<string, ${tsType(node.additionalProperties)}>`;
    default: throw new Error(`schema feature the generator does not know: ${JSON.stringify(node).slice(0, 80)}`);
  }
}

function fields(node, indent) {
  const required = new Set(node.required ?? []);
  return Object.entries(node.properties).map(([name, prop]) => {
    const doc = prop.description ? `${indent}/** ${prop.description} */\n` : '';
    return `${doc}${indent}${name}${required.has(name) ? '' : '?'}: ${tsType(prop)};\n`;
  }).join('');
}

function inlineObject(node) {
  return `{\n${fields(node, '    ')}  }`;
}

function declaration(name, node) {
  const doc = node.description ? `/** ${node.description} */\n` : '';
  if (node.type === 'object' && node.properties) return `${doc}export interface ${name} {\n${fields(node, '  ')}}\n`;
  return `${doc}export type ${name} = ${tsType(node)};\n`;
}

/** ajv copies the schema into its output, and the words only make that bigger. */
function withoutDocs(node) {
  if (Array.isArray(node)) return node.map(withoutDocs);
  if (node === null || typeof node !== 'object') return node;
  return Object.fromEntries(Object.entries(node).filter(([key, value]) => !((key === 'description' || key === 'title') && typeof value === 'string')).map(([key, value]) => [key, withoutDocs(value)]));
}

export function generate(schema) {
  const types = [declaration(schema.title, schema), ...Object.entries(schema.$defs).map(([name, node]) => declaration(name, node))];
  const ajv = makeAjv({ code: { source: true, esm: true } });
  const validate = ajv.compile(withoutDocs(schema));
  return {
    'snapshot-types.ts': `${HEADER}\n${types.join('\n')}`,
    'validate-snapshot.js': `${HEADER}${standaloneCode.default(ajv, validate)}\n`,
  };
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const files = generate(JSON.parse(readFileSync(SCHEMA, 'utf8')));
  for (const [name, text] of Object.entries(files)) writeFileSync(new URL(name, OUT), text);
  console.log(`wrote ${Object.keys(files).join(', ')}`);
}
