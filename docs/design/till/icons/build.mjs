#!/usr/bin/env node
/* Generates react/icons.tsx and ../mocks/assets/icons.js from svg/, map.json and react/iconFor.ts. Run: node icons/build.mjs. No dependencies, no network. */
import fs from 'node:fs';import path from 'node:path';import {stripTypeScriptTypes} from 'node:module';import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const map=JSON.parse(fs.readFileSync(here+'/map.json','utf8'));
const read=(dir,kind)=>fs.readdirSync(`${here}/svg/${dir}`).filter(f=>f.endsWith('.svg')).sort().map(f=>({name:f.slice(0,-4),kind,body:fs.readFileSync(`${here}/svg/${dir}/${f}`,'utf8').match(/<svg[^>]*>(.*)<\/svg>/s)[1]}));
const icons=[...read('lucide','line'),...read('brand','brand')];
const pascal=s=>s.split('-').map(w=>w[0].toUpperCase()+w.slice(1)).join('');
const jsx=b=>b.replace(/([a-z]+)-([a-z]+)=/g,(m,a,c)=>a+c[0].toUpperCase()+c.slice(1)+'=');
const tsx=`/* Generated by icons/build.mjs. Do not edit. Licences: ICONS.md. Single colour, currentColor only: colour stays with the row's meaning. */
import type { SVGProps } from 'react';

export type IconName =
${icons.map(i=>`  | '${i.name}'`).join('\n')};

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> { size?: number }

function line(body: React.ReactNode, { size = 22, strokeWidth = 1.75, ...rest }: IconProps) {
  return <svg aria-hidden="true" focusable="false" viewBox="0 0 24 24" width={size} height={size} fill="none" stroke="currentColor" strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round" {...rest}>{body}</svg>;
}
function solid(body: React.ReactNode, { size = 22, ...rest }: IconProps) {
  return <svg aria-hidden="true" focusable="false" viewBox="0 0 24 24" width={size} height={size} fill="currentColor" {...rest}>{body}</svg>;
}

${icons.map(i=>`export const ${pascal(i.name)}Icon = (p: IconProps) => ${i.kind==='line'?'line':'solid'}(<>${jsx(i.body)}</>, p);`).join('\n')}

export const ICONS: Record<IconName, (p: IconProps) => React.JSX.Element> = {
${icons.map(i=>`  '${i.name}': ${pascal(i.name)}Icon,`).join('\n')}
};

/** Decorative: the row's word is always beside it. */
export function Icon({ name, ...p }: IconProps & { name: IconName }) {
  const C = ICONS[name];
  return <C {...p} />;
}
`.replace("import type { SVGProps } from 'react';","import type React from 'react';\nimport type { SVGProps } from 'react';");
fs.writeFileSync(here+'/react/icons.tsx',tsx);
const src=fs.readFileSync(here+'/react/iconFor.ts','utf8').replace(/^import map .*$/m,'').replace(/^export /gm,'');
const fn=stripTypeScriptTypes(src,{mode:'strip'}).replace(/\n\s*\n+/g,'\n');
const js=`/* Generated by icons/build.mjs. Do not edit. Inlined icons so nothing is ever fetched, also from file://. Licences: ICONS.md. */
const TillIcons=(()=>{
const map=${JSON.stringify(map)};
${fn}
const SVG=${JSON.stringify(Object.fromEntries(icons.map(i=>[i.name,[i.kind==='line'?0:1,i.body]])))};
const svg=n=>{const [b,body]=SVG[n];return \`<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false" \${b?'fill="currentColor"':'fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round"'}>\${body}</svg>\`};
const choose=q=>iconFor({...q,group:map.mock_group_labels[q.group]||q.group});
/* html({name,group,confidence,unnamed}) or html({ui:'preview'}) */
const html=(q,cls='')=>{const c=q.ui?{name:map.ui[q.ui],kind:'category'}:q.icon?{name:q.icon,kind:'category'}:choose(q);return \`<i class="ico \${c.kind} \${cls}" data-ic="\${c.name}">\${svg(c.name)}</i>\`};
const hydrate=(root=document)=>root.querySelectorAll('i.ico:not([data-ic])').forEach(e=>{const d=e.dataset,q=d.ui?{ui:d.ui}:{name:d.name,group:d.group,confidence:d.confidence,unnamed:'unnamed' in d},t=document.createElement('template');t.innerHTML=html(q);const o=t.content.firstChild;o.className+=' '+e.className.replace('ico','').trim();e.replaceWith(o)});
return{iconFor,html,hydrate,svg};
})();
if(typeof document!=='undefined')TillIcons.hydrate();
`;
fs.writeFileSync(here+'/../mocks/assets/icons.js',js);
fs.writeFileSync(here+'/react/index.ts',`/* Import from here. Generated names in icons.tsx, the choice in iconFor.ts. */\nexport * from './icons';\nexport * from './iconFor';\n`);
console.log(icons.length,'icons',Buffer.byteLength(js),'bytes js',Buffer.byteLength(tsx),'bytes tsx');
